let current = "en";

/** Look a string up, falling back to English, then to the key itself. */
export function t(key, vars) {
  const table = STRINGS[current] || STRINGS.en;
  let out = table[key];
  if (out === undefined) out = STRINGS.en[key];
  if (out === undefined) return key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

export function setLanguage(code) {
  current = STRINGS[code] ? code : "en";
  document.documentElement.lang = current;
  applyTranslations();
  // Screens drawn from data (not data-i18n attributes) redraw on this.
  window.dispatchEvent(new CustomEvent("mt:lang", { detail: current }));
  return current;
}

export function getLanguage() {
  return current;
}

/** Rewrite every element carrying a data-i18n attribute. */
export function applyTranslations(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  root.querySelectorAll("[data-i18n-label]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nLabel));
  });
}

